"""Generate the Max for Live device the audio probes answer through.

Ports, addresses and field orders come from :mod:`live_maestro.probe_protocol`, so a
device and a harness that disagree cannot be built. The ``.maxpat`` written beside the
``.amxd`` is the same graph in a form ``git diff`` can show, and ``--check`` fails when
either file stopped matching this script.

Every object name was taken from the refpages of the Max that ships with Live 12 Suite.
Max draws an unknown object as a broken box, reports no error and measures nothing, so
an unverified name fails silently. The two branches share only the socket: one device
has to carry both because a Live restart is expensive.

Usage:
    python scripts/build_probe_device.py
    python scripts/build_probe_device.py --check
"""

from __future__ import annotations

import sys
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parent.parent
if str(REPO_ROOT / "src") not in sys.path:
    sys.path.insert(0, str(REPO_ROOT / "src"))

from live_maestro.maxgen import AMXD_AUDIO_EFFECT, DeviceBuild, Patch
from live_maestro.maxgen import main as maxgen_main
from live_maestro.probe_protocol import (
    BUFFER_ADDRESS,
    BUFFER_NAME,
    BUFFER_REPLY_ADDRESS,
    DEVICE_PORT,
    DUMP_ADDRESS,
    IMPULSE_PERIOD,
    PING_ADDRESS,
    PONG_ADDRESS,
    REC_MARK_REPLY_ADDRESS,
    REC_OPEN_ADDRESS,
    REC_START_ADDRESS,
    REC_STOP_ADDRESS,
    REPLY_PORT,
    TRACK_OPEN_ADDRESS,
    TRACK_START_ADDRESS,
    TRACK_STOP_ADDRESS,
)

DEVICE_NAME = "LiveMaestro_Probe"
DEFAULT_OUT = REPO_ROOT / "devices"

#: ``info~`` outlet indices, from its reference page. The object reports right to left,
#: so the sample rate at outlet 0 arrives last and every value is in place by then.
INFO_SAMPLERATE = 0
INFO_TOTAL_MS = 6
INFO_CHANNELS = 8


def _id_and_rest(patch: Patch, source: str, outlet: int) -> tuple[str, str]:
    """Split ``<request_id> <rest...>`` into the id box and the remainder box.

    ``zl slice 1`` puts the first atom out of the left outlet and everything after it
    out of the right. A path is not one atom when it holds spaces, which every Ableton
    factory sample path does, so the remainder is joined back into one symbol by the
    caller rather than read as a list.
    """
    split = patch.obj("zl slice 1")
    patch.link(source, outlet, split, 0)
    return split, split


def _as_path(patch: Patch, source: str, outlet: int, verb: str, target: str) -> None:
    """Join a possibly space split path back into one symbol and send it as ``verb``."""
    joined = patch.obj("tosymbol")
    patch.link(source, outlet, joined, 0)
    verbed = patch.obj(f"prepend {verb}")
    patch.link(joined, 0, verbed, 0)
    patch.link(verbed, 0, target, 0)


def build() -> dict[str, Any]:
    """Assemble the whole device graph."""
    patch = Patch()

    patch.comment(
        "LiveMaestro Probe. Throwaway spike device, generated by "
        "scripts/build_probe_device.py. Edit that script, not this patch."
    )
    patch.comment(
        f"Listens on UDP {DEVICE_PORT} and answers to 127.0.0.1:{REPLY_PORT}. "
        f"Driven by scripts/spike_probe.py."
    )

    # ---- audio path. The device sits in a chain and must not colour anything.
    plugin = patch.obj("plugin~ 1 2")
    plugout = patch.obj("plugout~ 1 2")
    patch.link(plugin, 0, plugout, 0)
    patch.link(plugin, 1, plugout, 1)

    recv = patch.obj(f"udpreceive {DEVICE_PORT}")
    send = patch.obj(f"udpsend 127.0.0.1 {REPLY_PORT}")
    router = patch.obj(
        f"route {BUFFER_ADDRESS} {DUMP_ADDRESS} {REC_OPEN_ADDRESS} "
        f"{REC_START_ADDRESS} {REC_STOP_ADDRESS} {PING_ADDRESS} "
        f"{TRACK_OPEN_ADDRESS} {TRACK_START_ADDRESS} {TRACK_STOP_ADDRESS}"
    )
    patch.link(recv, 0, router, 0)

    # ---- ping, so the harness can prove the device is loaded and listening before it
    # reads anything. Without it a silent device and a wrong port look the same.
    pong = patch.obj(f"prepend {PONG_ADDRESS}")
    patch.link(router, 5, pong, 0)
    patch.link(pong, 0, send, 0)

    # ---- spike 1: buffer~ against an encrypted factory sample.
    buffer_box = patch.obj(f"buffer~ {BUFFER_NAME} 100")
    info = patch.obj(f"info~ {BUFFER_NAME}")

    #: Holds the id of the request in flight, so the reply can be tied to it. Both the
    #: read and the write branch write here, and buffer~ bangs the same outlet for
    #: either, so a reply always names the request that caused it.
    pending = patch.obj("int 0")

    read_split, _ = _id_and_rest(patch, router, 0)
    patch.link(read_split, 0, pending, 1)
    _as_path(patch, read_split, 1, "replace", buffer_box)

    dump_split, _ = _id_and_rest(patch, router, 1)
    patch.link(dump_split, 0, pending, 1)
    _as_path(patch, dump_split, 1, "writewave", buffer_box)

    # buffer~'s right outlet bangs when a read or a write finished. Nothing bangs it
    # when one failed, which is why an unanswered request is the failure signal.
    done = patch.obj("t b b")
    patch.link(buffer_box, 1, done, 0)

    reply = patch.obj("pack 0 0. 0. 0.")
    patch.link(done, 1, info, 0)
    patch.link(info, INFO_SAMPLERATE, reply, 1)
    patch.link(info, INFO_TOTAL_MS, reply, 2)
    patch.link(info, INFO_CHANNELS, reply, 3)
    patch.link(done, 0, pending, 0)
    patch.link(pending, 0, reply, 0)

    buffer_reply = patch.obj(f"prepend {BUFFER_REPLY_ADDRESS}")
    patch.link(reply, 0, buffer_reply, 0)
    patch.link(buffer_reply, 0, send, 0)

    # ---- spike 2: what sfrecord~ does with the message that starts it.
    # A free running sample counter is the only clock both sides can see. The impulse
    # train it drives sits at known multiples of IMPULSE_PERIOD, so where the first
    # impulse lands in the file says where the file's sample zero was.
    # count~ constructs switched off and counts only after a bang, which its reference
    # page states on the left inlet and not in the object's description. Left unbanged
    # it holds 0, every sample is then 0 modulo the period, and the impulse train the
    # measurement rests on is a constant 1. live.thisdevice bangs once the device is
    # fully alive in Live, which loadbang does not guarantee.
    counter = patch.obj("count~")
    alive = patch.obj("live.thisdevice")
    patch.link(alive, 0, counter, 0)
    modulo = patch.obj(f"%~ {IMPULSE_PERIOD}")
    impulse = patch.obj("==~ 0")
    patch.link(counter, 0, modulo, 0)
    patch.link(modulo, 0, impulse, 0)

    recorder = patch.obj("sfrecord~ 1")
    patch.link(impulse, 0, recorder, 0)

    samptype = patch.message("samptype float32")
    patch.link(samptype, 0, recorder, 0)
    boot = patch.obj("loadbang")
    patch.link(boot, 0, samptype, 0)

    open_split, _ = _id_and_rest(patch, router, 2)
    _as_path(patch, open_split, 1, "open wave", recorder)

    # snapshot~ reports the counter at the last signal vector boundary, so the mark is
    # quantised to one vector and the recorder starts at the next one. That vector is
    # the floor under anything this measures, and the harness reports it as such.
    mark = patch.obj("snapshot~")
    patch.link(counter, 0, mark, 0)

    mark_pack = patch.obj("pack 0 0 0.")
    mark_reply = patch.obj(f"prepend {REC_MARK_REPLY_ADDRESS}")
    patch.link(mark, 0, mark_pack, 2)
    patch.link(mark_pack, 0, mark_reply, 0)
    patch.link(mark_reply, 0, send, 0)

    for outlet, phase in ((3, 1), (4, 0)):
        split, _ = _id_and_rest(patch, router, outlet)
        # trigger fires right to left, so this reads bottom up: take the counter
        # reading, set the phase beside it, run the recorder, and only then let the
        # request id land in the pack's hot inlet and send the reply. The id leaves
        # through outlet 0 as an int rather than a bang, because it is the value the
        # reply is keyed by and a bang would drop it.
        order = patch.obj("t i b b b")
        patch.link(split, 0, order, 0)
        patch.link(order, 3, mark, 0)
        phase_box = patch.message(str(phase))
        patch.link(order, 2, phase_box, 0)
        patch.link(phase_box, 0, mark_pack, 1)
        run = patch.message(str(phase))
        patch.link(order, 1, run, 0)
        patch.link(run, 0, recorder, 0)
        patch.link(order, 0, mark_pack, 0)

    # ---- capturing what an instrument on this track plays.
    # A recorder of its own rather than a switch on the first one: the impulse recorder
    # measures where recording begins and must have nothing else in its signal, and a
    # selector between them is one more thing that can be in the wrong position when a
    # measurement is taken.
    track_recorder = patch.obj("sfrecord~ 2")
    patch.link(plugin, 0, track_recorder, 0)
    patch.link(plugin, 1, track_recorder, 1)
    track_type = patch.message("samptype float32")
    patch.link(track_type, 0, track_recorder, 0)
    patch.link(boot, 0, track_type, 0)

    track_open = _id_and_rest(patch, router, 6)[0]
    _as_path(patch, track_open, 1, "open wave", track_recorder)
    for outlet, running in ((7, 1), (8, 0)):
        split = _id_and_rest(patch, router, outlet)[0]
        run = patch.message(str(running))
        patch.link(split, 0, run, 0)
        patch.link(run, 0, track_recorder, 0)

    return patch.to_patcher(
        "LiveMaestro Probe: buffer~ and sfrecord~ spikes, generated.",
        title=DEVICE_NAME,
        device_type=AMXD_AUDIO_EFFECT,
    )


DEVICE = DeviceBuild(
    name=DEVICE_NAME,
    build=build,
    generator="scripts/build_probe_device.py",
    contract="src/live_maestro/probe_protocol.py",
    out_default=DEFAULT_OUT,
    display_root=REPO_ROOT,
    device_type=AMXD_AUDIO_EFFECT,
    free_running=("plugin~", "udpreceive", "live.thisdevice", "loadbang"),
    terminal=("plugout~", "udpsend", "sfrecord~", "buffer~"),
)


if __name__ == "__main__":
    raise SystemExit(maxgen_main(DEVICE))
